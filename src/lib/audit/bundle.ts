/**
 * The downloadable report bundle: everything in a finished scan, packed as
 * a ZIP for handoff and archiving.
 *
 * Pure — it takes the report DTO (the same object the page renders) plus
 * screenshot bytes, so the bundle can never drift from the report the owner
 * reviewed. The route adds auth, ownership and the Pro gate; this module
 * only decides what goes in the archive.
 */

import { createZip, type ZipSource } from "@/lib/zip";
import { scoreBand, scoreFromCounts } from "./score";
import {
  CATEGORY_LABELS,
  SEVERITY_LABELS,
  SEVERITY_ORDER,
  type FindingDto,
  type ScanResultsDto,
} from "./types";

export interface BundleScreenshot {
  /** Stable filename stem, e.g. the page id prefix. */
  name: string;
  /** Page URL, recorded in the README so files map back to pages. */
  url: string;
  /** Raw PNG bytes. */
  png: Uint8Array;
}

function findingBlock(finding: FindingDto): string {
  const lines = [
    `## [${finding.severity}] ${finding.title}`,
    ``,
    `Rule: ${finding.ruleId} · Category: ${CATEGORY_LABELS[finding.category] ?? finding.category}`,
    finding.pageUrl ? `Page: ${finding.pageUrl}` : null,
    finding.wcagCriterion ? `WCAG: ${finding.wcagCriterion}` : null,
    finding.elementSelector ? `Selector: \`${finding.elementSelector}\`` : null,
    ``,
    finding.description,
    ``,
    `Why it matters: ${finding.whyMatters}`,
    ``,
    `Recommendation: ${finding.recommendation}`,
    finding.implementation ? `` : null,
    finding.implementation ? `How to fix: ${finding.implementation}` : null,
  ];
  return lines.filter((line) => line !== null).join("\n");
}

/**
 * The human-readable half of the bundle: score, counts, pages, every
 * finding with its fix. Markdown so it reads in any editor, diffs cleanly
 * in version control, and converts to PDF without tooling.
 */
export function renderReportMarkdown(results: ScanResultsDto): string {
  const score = scoreFromCounts(results.counts);
  const band = scoreBand(score);
  const { scan } = results;
  const lines = [
    `# Website audit — ${scan.normalizedUrl}`,
    ``,
    `Scanned ${scan.completedAt ?? scan.createdAt} · ${scan.pagesScanned} of ${scan.pagesTotal} pages · viewport ${scan.viewportWidth}×${scan.viewportHeight}.`,
    ``,
    `## Health score: ${score}/100 (${band.label})`,
    ``,
    band.blurb,
    ``,
    `## Findings by severity`,
    ``,
    ...SEVERITY_ORDER.map(
      (severity) =>
        `- ${SEVERITY_LABELS[severity]}: ${results.counts[severity]}`,
    ),
    ``,
    `## Pages`,
    ``,
    ...results.pages.map(
      (page) =>
        `- ${page.title ?? page.url} (${page.url}) — ` +
        (page.statusCode === null
          ? (page.errorMessage ?? "not analysed")
          : `HTTP ${page.statusCode}`),
    ),
    ``,
    `## Findings (${results.findings.length})`,
    ``,
    ...results.findings.map(findingBlock).flatMap((block) => [block, ``]),
    `---`,
    ``,
    `Limitations: automated rules cover a subset of WCAG 2.2; this report is not a certificate of conformance. Only the listed pages were checked, at one viewport; interactive states, content behind a login, other breakpoints and multi-page journeys are outside this stage.`,
  ];
  return lines.join("\n");
}

function bundleReadme(results: ScanResultsDto, screenshots: BundleScreenshot[]): string {
  const score = scoreFromCounts(results.counts);
  return [
    `Website audit bundle — ${results.scan.normalizedUrl}`,
    ``,
    `Health score ${score}/100 · ${results.counts.total} findings · ${results.pages.length} pages.`,
    ``,
    `Contents:`,
    `- report.md — the full report in Markdown, with every finding and fix.`,
    `- report.json — the same report as structured data.`,
    ...screenshots.map((shot, i) => `- screenshots/${shot.name}.png — capture of ${shot.url}${i === 0 ? " (the report's hero image)" : ""}.`),
    screenshots.length === 0
      ? "- (no screenshots were captured for this scan)"
      : "",
    `Generated by the ChromaBrew site audit. Screenshots are point-in-time captures at ${results.scan.viewportWidth}×${results.scan.viewportHeight}.`,
  ]
    .join("\n");
}

/** Assemble the archive. Screenshots are optional — a scan without captures still bundles. */
export function buildScanBundle(
  results: ScanResultsDto,
  screenshots: BundleScreenshot[],
): Uint8Array<ArrayBuffer> {
  const files: ZipSource[] = [
    { path: "report.md", content: renderReportMarkdown(results) },
    { path: "report.json", content: JSON.stringify(results, null, 2) },
    { path: "README.txt", content: bundleReadme(results, screenshots) },
    ...screenshots.map((shot) => ({
      path: `screenshots/${shot.name}.png`,
      content: shot.png,
    })),
  ];
  return createZip(files);
}
