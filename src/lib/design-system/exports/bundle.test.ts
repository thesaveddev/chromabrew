import { describe, expect, it } from "vitest";
import { buildDesignSystem, normaliseConfig } from "..";
import { bundleAdapter } from "./bundle";
import { cssAdapter } from "./css";
import { jsonAdapter } from "./json";
import type { ExportContext } from "./context";

/**
 * The bundle writer stores files uncompressed, so file names and contents
 * appear literally in the decoded bytes — no ZIP parser needed to assert on
 * the deliverable, just the same read any recipient's unzip performs.
 */
function decoded(result: { code: string }): string {
  return Buffer.from(result.code, "base64").toString("utf8");
}

function system() {
  return buildDesignSystem(
    normaliseConfig({
      primary: "#47003a",
      paletteStrategy: "complementary",
      radiusStyle: "soft",
      typeRatio: 1.25,
    }),
  );
}

const CTX: ExportContext = {
  projectName: "Acme Dashboard",
  clientName: "Acme Inc",
  versionLabel: "v3",
  generatedAt: new Date(Date.UTC(2026, 9, 26)),
};

describe("bundleAdapter — legacy output without a context", () => {
  it("keeps the historical zip name and layout", () => {
    const sys = system();
    const result = bundleAdapter.generate(sys);
    expect(result.suggestedFilename).toBe("chromabrew-design-system.zip");
    const zip = decoded(result);
    expect(zip).toContain("README.md");
    expect(zip).toContain("css/design-tokens.css");
    expect(zip).toContain("design-tools/figma/figma-tokens.json");
  });
});

describe("bundleAdapter — white-label packaging with a context", () => {
  it("names the zip for the project and version", () => {
    expect(bundleAdapter.generate(system(), CTX).suggestedFilename).toBe(
      "acme-dashboard-design-system-v3.zip",
    );
  });

  it("slugs every path and filename", () => {
    const zip = decoded(bundleAdapter.generate(system(), CTX));
    expect(zip).toContain("acme-dashboard/css/acme-dashboard-design-tokens.css");
    expect(zip).toContain("acme-dashboard/json/acme-dashboard-design-tokens.json");
    expect(zip).toContain("acme-dashboard/tailwind/acme-dashboard-tailwind-theme.css");
    expect(zip).toContain("acme-dashboard/shadcn/acme-dashboard-shadcn-theme.css");
    expect(zip).toContain("acme-dashboard/design-tools/figma/acme-dashboard-figma-tokens.json");
    expect(zip).not.toContain("chromabrew-design-system.zip");
  });

  it("stamps headers with project, client and version", () => {
    const zip = decoded(bundleAdapter.generate(system(), CTX));
    expect(zip).toContain("Acme Dashboard design tokens");
    expect(zip).toContain("Prepared for Acme Inc · v3 · 26 Oct 2026");
  });

  it("presents the bundle with a README naming project, client and contents", () => {
    const zip = decoded(bundleAdapter.generate(system(), CTX));
    expect(zip).toContain("# Acme Dashboard — Design System v3");
    expect(zip).toContain("Prepared for: Acme Inc");
    expect(zip).toContain("Generated: 26 Oct 2026");
    expect(zip).toContain("Source colour: `#47003a`");
    expect(zip).toContain("acme-dashboard/css/acme-dashboard-design-tokens.css");
    expect(zip).toContain("## Accessibility");
    expect(zip).toContain("Generated with ChromaBrew.");
  });
});

describe("white-label headers — token structure untouched", () => {
  it("extends the JSON description without changing the token shape", () => {
    const result = jsonAdapter.generate(system(), CTX);
    expect(result.suggestedFilename).toBe("acme-dashboard-design-tokens.json");
    const payload = JSON.parse(result.code) as {
      $description: string;
      primitive: { color: { brand: Record<string, { $type: string; $value: string }> } };
      semantic: {
        light: Record<string, { $type: string; $value: string }>;
        dark: Record<string, { $type: string; $value: string }>;
      };
    };
    expect(payload.$description).toContain("Acme Dashboard");
    expect(payload.$description).toContain("Prepared for Acme Inc · v3");
    // The structure importers read is exactly what it was: brand scale,
    // palette and both semantic themes as DTCG color tokens.
    expect(Object.keys(payload.primitive.color.brand).length).toBeGreaterThan(0);
    expect(payload.semantic.light.background.$type).toBe("color");
    expect(typeof payload.semantic.light.background.$value).toBe("string");
    expect(typeof payload.semantic.dark.background.$value).toBe("string");
  });

  it("leaves the default single-file output byte-identical in shape", () => {
    const result = cssAdapter.generate(system());
    expect(result.suggestedFilename).toBe("design-tokens.css");
    expect(result.code).toContain("design tokens");
    expect(result.code).toContain("Generated by ChromaBrew");
    expect(result.code).not.toContain("Prepared for");
  });
});
